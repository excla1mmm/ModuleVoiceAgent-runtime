"""PBX tenants and their credentials.

Every PBX has an id (``pbx-...``) and a secret token generated by the module. The runtime stores only the
SHA-256 of each token, in a JSON file maintained by the operator::

    {"tenants": [{"id": "pbx-1a2b3c4d5e6f", "name": "ACME", "token_sha256": ["<hex>", "<hex of the next token>"]}]}

Several hashes per tenant allow a token rotation without downtime: add the new hash, rotate the token on
the PBX, remove the old hash. The file is re-read when it changes; no restart is needed.

Optional per-tenant limits: ``max_calls`` (concurrent calls of this PBX) and ``max_agents`` (bundles it may
load); they override ``VA_MAX_CALLS_PER_TENANT`` / ``VA_MAX_AGENTS_PER_TENANT``.

With many PBXs ``VA_TENANTS_FILE`` may point at a directory: every ``*.json`` file in it holds either
``{"tenants": [...]}`` or a single tenant object, so each registration is its own drop-in file and a
broken file disables only that PBX, not all of them.

Asterisk authenticates the media WebSocket with Basic auth (username = PBX id, password = token); the PBX
module calls the HTTPS API with ``Authorization: Bearer <PBX id>.<token>``.
"""

from __future__ import annotations

import base64
import binascii
import hashlib
import hmac
import json
import logging
import re
import threading
import time
from dataclasses import dataclass
from pathlib import Path

TENANT_ID = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_-]{2,63}$")
RECHECK_INTERVAL_S = 5.0
log = logging.getLogger(__name__)


def token_hash(token: str) -> str:
    return hashlib.sha256(token.encode("utf-8")).hexdigest()


@dataclass(frozen=True)
class Tenant:
    id: str
    name: str
    hashes: tuple[str, ...]
    max_calls: int | None = None  # None = the service-wide per-tenant default
    max_agents: int | None = None


class TenantRegistry:
    def __init__(self, path: Path):
        self.path = path
        self._tenants: dict[str, Tenant] = {}
        self._mtime: float | None = None
        self._checked_at = 0.0
        self._lock = threading.Lock()

    @classmethod
    def from_mapping(cls, data: dict) -> TenantRegistry:
        registry = cls(Path("/nonexistent"))
        registry._tenants = parse_tenants(data)
        registry._checked_at = float("inf")
        return registry

    def __len__(self) -> int:
        self._refresh()
        return len(self._tenants)

    def get(self, tenant_id: str) -> Tenant | None:
        self._refresh()
        return self._tenants.get(tenant_id)

    def ids(self) -> list[str]:
        self._refresh()
        return list(self._tenants)

    def verify(self, tenant_id: str, secret: str) -> bool:
        self._refresh()
        tenant = self._tenants.get(tenant_id)
        if tenant is None or not secret:
            return False
        digest = token_hash(secret)
        # compare against every hash so the time does not depend on which one matched
        matched = False
        for expected in tenant.hashes:
            matched |= hmac.compare_digest(digest, expected)
        return matched

    def _refresh(self) -> None:
        now = time.monotonic()
        if now - self._checked_at < RECHECK_INTERVAL_S:
            return
        with self._lock:
            self._checked_at = now
            try:
                if self.path.is_dir():
                    self._refresh_dir()
                else:
                    self._refresh_file()
            except OSError:
                if self._tenants:
                    log.warning("tenants file %s is not readable, keeping the loaded tenants", self.path)

    def _refresh_file(self) -> None:
        mtime = self.path.stat().st_mtime
        if mtime == self._mtime:
            return
        try:
            self._tenants = parse_tenants(json.loads(self.path.read_text(encoding="utf-8")))
            self._mtime = mtime
            log.info("loaded %d tenants from %s", len(self._tenants), self.path)
        except (OSError, ValueError) as exc:
            log.error("tenants file %s is invalid, keeping the loaded tenants: %s", self.path, exc)

    def _refresh_dir(self) -> None:
        files = sorted(f for f in self.path.iterdir() if f.suffix == ".json" and f.is_file())
        signature = hash(tuple((f.name, f.stat().st_mtime_ns, f.stat().st_size) for f in files))
        if signature == self._mtime:
            return
        tenants: dict[str, Tenant] = {}
        for file in files:
            try:
                data = json.loads(file.read_text(encoding="utf-8"))
                if isinstance(data, dict) and "tenants" not in data:
                    data = {"tenants": [data]}  # one tenant per file
                for tenant_id, tenant in parse_tenants(data).items():
                    if tenant_id in tenants:
                        log.error("tenant %s is defined twice (%s), keeping the first definition", tenant_id, file)
                        continue
                    tenants[tenant_id] = tenant
            except (OSError, ValueError) as exc:
                log.error("tenants file %s is invalid and was skipped: %s", file, exc)
        self._tenants = tenants
        self._mtime = signature
        log.info("loaded %d tenants from %d files in %s", len(tenants), len(files), self.path)


def parse_tenants(data: dict) -> dict[str, Tenant]:
    if not isinstance(data, dict) or not isinstance(data.get("tenants"), list):
        raise ValueError('expected {"tenants": [...]}')
    tenants: dict[str, Tenant] = {}
    for item in data["tenants"]:
        if not isinstance(item, dict):
            raise ValueError("a tenant must be an object")
        tenant_id = str(item.get("id", ""))
        if not TENANT_ID.match(tenant_id):
            raise ValueError(f"invalid tenant id {tenant_id!r}")
        hashes = item.get("token_sha256", [])
        if isinstance(hashes, str):
            hashes = [hashes]
        clean = tuple(h.lower() for h in hashes if isinstance(h, str) and re.fullmatch(r"[0-9a-fA-F]{64}", h))
        if not clean:
            raise ValueError(f"tenant {tenant_id} has no valid token_sha256")
        tenants[tenant_id] = Tenant(tenant_id, str(item.get("name", "")), clean,
                                    max_calls=_limit(item, "max_calls", tenant_id),
                                    max_agents=_limit(item, "max_agents", tenant_id))
    return tenants


def _limit(item: dict, key: str, tenant_id: str) -> int | None:
    value = item.get(key)
    if value is None:
        return None
    if isinstance(value, bool) or not isinstance(value, int) or value < 0:
        raise ValueError(f"tenant {tenant_id}: {key} must be a non-negative integer")
    return value


def basic_credentials(header: str) -> tuple[str, str] | None:
    if not header.lower().startswith("basic "):
        return None
    try:
        decoded = base64.b64decode(header[6:].strip(), validate=True).decode("utf-8")
    except (binascii.Error, UnicodeDecodeError):
        return None
    user, sep, password = decoded.partition(":")
    return (user, password) if sep else None


def bearer_credentials(header: str) -> tuple[str, str] | None:
    if not header.lower().startswith("bearer "):
        return None
    tenant_id, sep, secret = header[7:].strip().partition(".")
    return (tenant_id, secret) if sep else None


def authenticate(header: str, registry: TenantRegistry, scheme: str) -> str | None:
    """Returns the tenant id for valid credentials of the given scheme ("basic" or "bearer")."""
    creds = basic_credentials(header) if scheme == "basic" else bearer_credentials(header)
    if creds is None:
        return None
    tenant_id, secret = creds
    return tenant_id if registry.verify(tenant_id, secret) else None
