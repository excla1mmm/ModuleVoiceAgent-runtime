import pytest

from voice_agent_runtime.normalize import normalize, plural_form


@pytest.mark.parametrize("text, expected", [
    # prices exactly as the knowledge base writes them (the model used to spell 2900 as "девятьсот")
    ("Тариф «Старт» — 2900 рублей в месяц.", "Тариф Старт — две тысячи девятьсот рублей в месяц."),
    ("«Бизнес» — 12900 ₽/мес", "Бизнес — двенадцать тысяч девятьсот рублей в месяц"),
    ("Подключение стоит 15000 рублей", "Подключение стоит пятнадцать тысяч рублей"),
    ("21 руб. за минуту", "двадцать один рубль за минуту"),
    # genitive after prepositions, units agree with the number
    ("до 100 Мбит/с", "до ста мегабит в секунду"),
    ("до 1 Гбит/с", "до одного гигабита в секунду"),
    ("до 2 Гбит/с", "до двух гигабит в секунду"),
    ("скорость 1 Гбит/с", "скорость один гигабит в секунду"),
    ("скорость 2 Гбит/с", "скорость два гигабита в секунду"),
    ("от 3 до 10 рабочих дней", "от трёх до десяти рабочих дней"),
    ("скидка 10%", "скидка десять процентов"),
    ("7 мин. пешком", "семь минут пешком"),
    # times and dates
    ("с 9:00 до 19:00", "с девяти до девятнадцати"),
    ("суббота с 10:00 до 15:30", "суббота с десяти до пятнадцати тридцати"),
    ("приходите в 14:00", "приходите в четырнадцать часов"),
    ("в 21:00", "в двадцать один час"),
    ("в 14:30", "в четырнадцать тридцать"),
    ("в 9:05", "в девять ноль пять"),
    ("до 10 числа следующего месяца", "до десятого числа следующего месяца"),
    ("с 1 числа", "с первого числа"),
    ("к 5 числу", "к пятому числу"),
    ("1 января", "первого января"),
    # phones in groups, codes digit by digit
    ("+7 (495) 123-45-67", "семь, четыреста девяносто пять, сто двадцать три, сорок пять, шестьдесят семь"),
    ("код 007", "код ноль ноль семь"),
    # abbreviations, Latin, domains and e-mails
    ("ул. Профсоюзная, д. 65, корп. 1", "улица Профсоюзная, дом шестьдесят пять, корпус один"),
    ("Личный кабинет — lk.example.ru", "Личный кабинет — эл кей точка экзампл точка ру"),
    ("пишите на hr@example.ru", "пишите на эйч ар собака экзампл точка ру"),
    ("бесплатный Wi-Fi", "бесплатный вай фай"),
    ("№ 5", "номер пять"),
])
def test_normalize(text, expected):
    assert normalize(text) == expected


def test_thousands_with_spaces_are_one_number():
    assert normalize("2 900 рублей") == "две тысячи девятьсот рублей"


@pytest.mark.parametrize("n, genitive, expected", [
    (1, False, "рубль"), (2, False, "рубля"), (5, False, "рублей"), (11, False, "рублей"), (21, False, "рубль"),
    (1, True, "рубля"), (2, True, "рублей"), (21, True, "рубля"), (11, True, "рублей"),
])
def test_plural_form(n, genitive, expected):
    assert plural_form(n, ("рубль", "рубля", "рублей"), genitive) == expected
